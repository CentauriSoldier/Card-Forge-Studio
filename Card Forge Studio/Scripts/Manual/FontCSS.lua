--[[!
@fqxn CFS.Manual.FontCSS
@desc Translates Studio's existing parsed font-style settings into web CSS. Uses FontStyle.Parse and the existing INI reader for inheritance and CFG color resolution. Never scans, installs or copies fonts.
!]]

local INI		= require("Plugins.INI");
local JSON		= require("Manual.Lib.dkjson");
local Documents	= require("Manual.Documents");
local FontCSS	= {};
local StyleAliases = require("StyleAliases");

--[[!
@fqxn CFS.Manual.FontCSS.Private.Functions.color
@desc Converts Studio's packed RRGGBBAA color into CSS rgba channels.
@param number nColor Existing parsed Studio color.
@return string sCSS CSS color.
@vis private
!]]
local function color(nColor)
	return string.format("rgba(%d,%d,%d,%.6g)", (nColor >> 24) & 255, (nColor >> 16) & 255, (nColor >> 8) & 255, (nColor & 255) / 255);
end

--[[!
@fqxn CFS.Manual.FontCSS.Functions.generate
@desc Generates game font classes and inline-size overrides from the bound game's current Styles.ini. Retains known tag display spelling. CSS approximates native shadows/glow; bevel/wear are intentionally reported as unsupported, matching the prototype's limitations. Rejects source changes during generation.
@param string pGame Bound game data root.
@param string sPrevious Previous generated CSS, used only for display-name spelling.
@return string sCSS Generated classes without font-face file loading.
@return table tWarnings CSS effect limitations encountered.
!]]
function FontCSS.generate(pGame, sPrevious)
	local pINI		= pGame.."/Styles.ini";
	local sOriginal	= Documents.read(pINI);
	local oReader	= INI.CreateReader(pINI, false);
	local tNames	= oReader.GetSectionNames();
	local tLabels	= {};
	local tCSS		= {"/* Generated by Studio from the active game's Styles.ini. */", "/* Fonts are resolved by the operating system; CSS effects approximate native drawing. */", ""};
	local tWarnings	= {};
	for sLabel, sClass in (sPrevious or ""):gmatch("/%*%s*style:%s*([%w_-]+)%s*%*/%s*%.font%-([%w_-]+)") do tLabels[sClass:lower()] = sLabel; end
	local tAliases = StyleAliases.read(oReader);
	local tAliasNames = {};
	for sAlias in pairs(tAliases) do tAliasNames[#tAliasNames + 1] = sAlias; end
	table.sort(tAliasNames);
	for _, sAlias in ipairs(tAliasNames) do
		tCSS[#tCSS + 1] = "/* alias: "..sAlias.." = "..tAliases[sAlias].." */";
	end
	table.sort(tNames);
	for _, sName in ipairs(tNames) do
		local tParsed	= assert(CFS.FontStyle.Parse(sName, oReader), "Cannot parse game font style: "..sName);
		local tOptions	= tParsed.FontOptions;
		local nEm		= math.max(1, tParsed.FontSize * 4 / 3);
		local tProps	= {};
		local tShadows	= {};
		local tDecorations = {};
		assert(sName:match("^[A-Za-z_][A-Za-z0-9_-]*$"), "Invalid style name for web CSS: "..sName);

		--[[!
		@fqxn CFS.Manual.FontCSS.Private.Functions.fAdd
		@desc Appends one selected-style CSS declaration.
		@param string sProperty CSS property.
		@param string sValue Serialized CSS value.
		@vis private
		!]]
		local function fAdd(sProperty, sValue) tProps[#tProps + 1] = "\t"..sProperty..": "..sValue..";"; end

		--[[!
		@fqxn CFS.Manual.FontCSS.Private.Functions.fDistance
		@desc Converts native pixel distances to em so inline tags retain proportional effects.
		@param number nPixels Native pixel distance.
		@return string sEm CSS distance.
		@vis private
		!]]
		local function fDistance(nPixels) return string.format("%.6gem", nPixels / nEm); end
		fAdd("font-family", JSON.encode(tParsed.FontFamily)..", sans-serif");
		fAdd("font-size", tParsed.FontSize.."pt");
		fAdd("font-weight", tOptions.Bold and "700" or "400");
		fAdd("font-style", tOptions.Italic and "italic" or "normal");
		fAdd("font-synthesis", "weight style");
		fAdd("color", color(tParsed.FontColor));
		fAdd("letter-spacing", fDistance(tParsed.LetterSpacing));
		if (tOptions.Underline) then tDecorations[#tDecorations + 1] = "underline"; end
		if (tOptions.StrikeOut) then tDecorations[#tDecorations + 1] = "line-through"; end
		fAdd("text-decoration-line", #tDecorations > 0 and table.concat(tDecorations, " ") or "none");
		if (tParsed.ShadowEnabled) then tShadows[#tShadows + 1] = fDistance(tParsed.ShadowX).." "..fDistance(tParsed.ShadowY).." "..fDistance(tParsed.ShadowSoftness and tParsed.ShadowRadius or 0).." "..color(tParsed.ShadowColor); end
		if (tParsed.D3Enabled) then
			assert(tParsed.D3Depth <= 128, "3DDepth exceeds 128 CSS layers.");
			for nStep = 1, math.max(0, tParsed.D3Depth) do tShadows[#tShadows + 1] = fDistance(nStep * tParsed.D3StepX).." "..fDistance(nStep * tParsed.D3StepY).." 0 "..color(tParsed.D3Color); end
		end
		if (tParsed.GlowEnabled) then tShadows[#tShadows + 1] = "0 0 "..fDistance(tParsed.GlowRadius).." "..color(tParsed.GlowColor); tWarnings.Glow = "Glow uses a CSS approximation."; end
		fAdd("text-shadow", #tShadows > 0 and table.concat(tShadows, ", ") or "none");
		fAdd("-webkit-text-stroke", tParsed.OutlineEnabled and fDistance(math.max(0, tParsed.OutlineThickness)).." "..color(tParsed.OutlineColor) or "0 transparent");
		fAdd("paint-order", "stroke fill");
		if (tParsed.GradientEnabled) then
			local tStops = {};
			for _, tStop in ipairs(CFS.FontStyle.ParseGradientStops(tParsed.GradientStopsText)) do tStops[#tStops + 1] = color(tStop.Color).." "..string.format("%.6g%%", tStop.Position * 100); end
			fAdd("background-image", "linear-gradient("..(tParsed.GradientDirection == "Horizontal" and "to right" or "to bottom")..", "..table.concat(tStops, ", ")..")");
			fAdd("background-clip", "text"); fAdd("-webkit-background-clip", "text"); fAdd("-webkit-text-fill-color", "transparent");
		end
		if (tParsed.BackgroundEnabled) then fAdd("background-color", color(tParsed.BackgroundColor)); fAdd("padding", fDistance(tParsed.BackgroundPadding)); end
		if (tParsed.WearEnabled) then tWarnings.Wear = "Wear has no exact CSS mapping."; end
		if (tParsed.BevelEnabled == "true" or tParsed.BevelEnabled == true) then tWarnings.Bevel = "Bevel has no exact CSS mapping."; end
		tCSS[#tCSS + 1] = "/* style: "..(tLabels[sName:lower()] or sName).." */\n.font-"..sName:lower().." {\n"..table.concat(tProps, "\n").."\n}\n.font-"..sName:lower().."[data-inline] { font-size: inherit; }\n";
	end
	assert(Documents.read(pINI) == sOriginal, "Styles.ini changed during generation; try again.");
	return table.concat(tCSS, "\n"), tWarnings;
end

--[[!
@fqxn CFS.Manual.FontCSS.Functions.lookup
@desc Maps accepted tags to canonical CSS class names using generated alias metadata, without duplicate style rules.
@param string sCSS Generated game stylesheet.
@return table tStyles Lowercase canonical and alias tags mapped to canonical class names.
!]]
function FontCSS.lookup(sCSS)
	local tStyles = {};
	for sName in sCSS:gmatch("%.font%-([A-Za-z_][A-Za-z0-9_-]*)%s*[%[{]") do
		tStyles[sName:lower()] = sName:lower();
	end
	for sAlias, sName in sCSS:gmatch("/%*%s*alias:%s*([%w_-]+)%s*=%s*([%w_-]+)%s*%*/") do
		assert(tStyles[sName:lower()], "Missing alias target: "..sName);
		tStyles[sAlias:lower()] = sName:lower();
	end
	return tStyles;
end

return FontCSS;
