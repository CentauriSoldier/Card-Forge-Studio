--[[!
@fqxn CFS.Manual.PDFLayout
@desc Pure Lua pagination for the manual's existing Lua-rendered content. Preserves
    section order, quicksheets, glossary links, tables and inline formatting without
    a browser. Font resolution is supplied by the caller through explicit files.
    Produces a positioned display list before writing, so contents page numbers
    and forward links use final page locations. Visual options belong to the caller.
!]]

local assert       = assert;
local error        = error;
local ipairs       = ipairs;
local pairs        = pairs;
local tonumber     = tonumber;
local tostring     = tostring;
local rawtype      = rawtype or type;
local math         = math;
local string       = string;
local table        = table;
local utf8         = utf8;
local PDF          = require("Manual.PDF");
local Document     = require("Manual.Document");
local _tEntities   = {
    amp = "&", lt = "<", gt = ">", quot = '"', apos = "'", nbsp = "\194\160",
    copy = "©", reg = "®", trade = "™", ndash = "–", mdash = "—", hellip = "…",
    lsquo = "‘", rsquo = "’", ldquo = "“", rdquo = "”", bull = "•", middot = "·",
    times = "×", divide = "÷", plusmn = "±", minus = "−", deg = "°", euro = "€",
    pound = "£", yen = "¥", cent = "¢", le = "≤", ge = "≥", ne = "≠",
    larr = "←", rarr = "→", uarr = "↑", darr = "↓", harr = "↔", alpha = "α",
    beta = "β", gamma = "γ", Delta = "Δ", pi = "π", Omega = "Ω", infin = "∞",
};
local PDFLayout    = {};

--[[!
@fqxn CFS.Manual.PDFLayout.Private.Functions.decode
@desc Decodes supported HTML entities from trusted renderer output. Unrecognized
    named entities fail explicitly rather than silently changing document text.
@param string sText Encoded text or attribute.
@return string sText UTF-8 text.
@vis private
!]]
local function decode(sText)
    return (sText:gsub("&([^;]+);", function(sEntity)
        local nCode;

        if (sEntity:match("^#[xX]%x+$")) then nCode = tonumber(sEntity:sub(3), 16);
        elseif (sEntity:match("^#%d+$")) then nCode = tonumber(sEntity:sub(2)); end
        if (nCode) then
            assert(nCode > 0 and nCode <= 0x10FFFF and (nCode < 0xD800 or nCode > 0xDFFF), "Invalid PDF text entity: &"..sEntity..";");
            return utf8.char(nCode);
        end
        return assert(_tEntities[sEntity], "Unsupported PDF text entity: &"..sEntity..";");
    end));
end

--[[!
@fqxn CFS.Manual.PDFLayout.Private.Functions.parse
@desc Parses only the balanced semantic markup generated by Manual.Document.
    This is not an arbitrary HTML/CSS browser or an external-document importer.
@param string sHTML Complete Lua-generated manual document.
@return table tRoot Semantic body tree.
@vis private
!]]
local function parse(sHTML)
    local sBody = assert(sHTML:match("<body[^>]*>(.*)</body>"), "PDF document is missing its body.");
    local tRoot = {tag = "body", attributes = {}, children = {}};
    local tStack = {tRoot};
    local nOffset = 1;

    while (nOffset <= #sBody) do
        local nFirst, nLast, sMarkup = sBody:find("<([^>]+)>", nOffset);
        local tParent = tStack[#tStack];

        if (not nFirst) then
            tParent.children[#tParent.children + 1] = {tag = "text", text = decode(sBody:sub(nOffset))};
            break;
        end
        if (nFirst > nOffset) then
            tParent.children[#tParent.children + 1] = {tag = "text", text = decode(sBody:sub(nOffset, nFirst - 1))};
        end
        if (sMarkup:sub(1, 1) == "/") then
            local sTag = sMarkup:match("^/([%w]+)");

            assert(#tStack > 1 and tStack[#tStack].tag == sTag, "Unbalanced PDF markup: "..sMarkup);
            tStack[#tStack] = nil;
        elseif (sMarkup:sub(1, 1) ~= "!") then
            local sTag = assert(sMarkup:match("^([%w]+)"), "Invalid PDF markup.");
            local tNode = {tag = sTag, attributes = {}, children = {}};

            for sName, _, sValue in sMarkup:gmatch("([%w_:-]+)%s*=%s*(['\"])(.-)%2") do
                tNode.attributes[sName] = decode(sValue);
            end
            tParent.children[#tParent.children + 1] = tNode;
            if (not ({br = true, hr = true, img = true, input = true, meta = true, link = true})[sTag] and not sMarkup:match("/%s*$")) then
                assert(#tStack < 128, "PDF markup nesting exceeds 128 levels.");
                tStack[#tStack + 1] = tNode;
            end
        end
        nOffset = nLast + 1;
    end

    assert(#tStack == 1, "PDF markup has an unclosed element.");
    return tRoot;
end

--[[!
@fqxn CFS.Manual.PDFLayout.Private.Functions.hasClass
@desc Checks an exact renderer class without interpreting CSS.
@param table tNode Semantic element.
@param string sClass Class name.
@return boolean bFound Whether the class exists.
@vis private
!]]
local function hasClass(tNode, sClass)
    return (" "..(tNode.attributes and tNode.attributes.class or "").." "):find(" "..sClass.." ", 1, true) ~= nil;
end

--[[!
@fqxn CFS.Manual.PDFLayout.Private.Functions.plain
@desc Collects semantic text, preserving explicit line breaks.
@param table tNode Semantic node.
@return string sText Plain UTF-8 text.
@vis private
!]]
local function plain(tNode)
    local tText = {};

    if (tNode.tag == "text") then return tNode.text; end
    if (tNode.tag == "br") then return "\n"; end
    for _, tChild in ipairs(tNode.children) do tText[#tText + 1] = plain(tChild); end
    return table.concat(tText);
end

--[[!
@fqxn CFS.Manual.PDFLayout.Private.Functions.copy
@desc Copies a flat style descriptor; nested font/color descriptors remain read-only.
@param table tSource Source descriptor.
@return table tCopy Independent descriptor.
@vis private
!]]
local function copy(tSource)
    local tCopy = {};

    for sKey, vValue in pairs(tSource) do tCopy[sKey] = vValue; end
    return tCopy;
end

--[[!
@fqxn CFS.Manual.PDFLayout.Functions.build
@desc Paginates a saved manual snapshot using explicit fonts. Honors trim, bleed,
    mirrored margins and section/quicksheet order. Tables repeat headers and split
    long rows. Heading/body spacing and widow handling use measured font metrics.
    Unsupported styles/entities/assets fail; content is never silently discarded.
@param table tData Snapshot accepted by Manual.Document.build.
@param table tSettings Validated settings with pdf dimensions in inches.
@param table tOptions fonts maps regular/bold/italic/boldItalic/code to {path, face}.
    Optional resolveFont(style) supplies other families. styles or resolveStyle(name)
    provide native descriptors for custom style tags. Descriptors support size,
    color (RGB zero-to-one), bold, italic, underline, strike, spacing, family and font.
    Optional bodySize, headingSizes, lineSpacing, paragraphSpacing, headerSize,
    footerSize, showHeader, showFooter, imageDPI, maxPages and maxTableColumns tune
    layout. decoratePage(document, page, index, total, phase) optionally draws
    background/foreground decorations using the writer API. checkpoint() may
    process native events; cancelled() reports cancellation.
    onProgress(stage, message, pageCount) receives actual pagination/render milestones.
@return table tResult document, pageCount, destinations, headings and page plans.
    The caller owns staged saving/publication through document.save.
!]]
function PDFLayout.build(tData, tSettings, tOptions)
    local tPDF = assert(tSettings and tSettings.pdf, "Missing PDF layout settings.");
    local oDocument = PDF.create({Title = tData.context.gameName});
    local tRoot;
    local tFontCache, tImageCache, tMeasureCache = {}, {}, {};
    local tDestinations, tHeadings, tPagePlans = {}, {}, {};
    local tPendingAnchors = {};
    local tPendingMarker;
    local tStyles, tFileTargets = {}, {};
    local tBase;
    local nWidth, nHeight, nBleed, nTop, nBottom, nInside, nOutside;
    local nContentWidth;
    local nPage, nY = 0, 0;
    local tCurrent;
    local fCheckpoint;
    local fFont;
    local fMeasure;
    local fMetrics;
    local fInline;
    local fWrap;
    local fNewPage;
    local fEnsure;
    local fAnchor;
    local fLine;
    local fParagraph;
    local fImage;
    local fImageData;
    local fTable;
    local fWalk;
    local fLink;

    tOptions = tOptions or {};
    assert(tPDF.units == "in", "PDF layout dimensions must use inches.");
    for _, sKey in ipairs({"width", "height", "bleed", "marginTop", "marginBottom", "marginInside", "marginOutside"}) do
        local nValue = tPDF[sKey];

        assert(rawtype(nValue) == "number" and nValue == nValue and nValue >= 0 and nValue < math.huge, "Invalid PDF layout setting: "..sKey);
    end
    nBleed = tPDF.bleed * 72;
    nWidth, nHeight = tPDF.width * 72 + nBleed * 2, tPDF.height * 72 + nBleed * 2;
    nTop, nBottom = nBleed + tPDF.marginTop * 72, nBleed + tPDF.marginBottom * 72;
    nInside, nOutside = nBleed + tPDF.marginInside * 72, nBleed + tPDF.marginOutside * 72;
    nContentWidth = nWidth - nInside - nOutside;
    assert(nContentWidth > 24 and nHeight - nTop - nBottom > 48, "PDF margins leave insufficient room for manual content.");
    assert((tOptions.bodySize or 11) > 0 and (tOptions.lineSpacing or 1.25) >= 1, "Invalid PDF text sizing.");
    assert((tOptions.imageDPI or 96) > 0, "Image DPI must be positive.");
    for _, sName in ipairs({"bodySize", "lineSpacing", "paragraphSpacing", "headerSize", "footerSize", "imageDPI", "maxPages", "maxTableColumns"}) do
        local nValue = tOptions[sName];

        if (nValue ~= nil) then
            assert(rawtype(nValue) == "number" and nValue == nValue and nValue < math.huge
                and (sName == "paragraphSpacing" and nValue >= 0 or nValue > 0), "Invalid PDF layout option: "..sName);
        end
    end
    assert(tOptions.fonts or tOptions.resolveFont, "PDF layout requires explicit font files or a font resolver.");
    for sName, tStyle in pairs(tOptions.styles or {}) do tStyles[sName:lower()] = tStyle; end
    tBase = {size = tOptions.bodySize or 11, color = tOptions.textColor or {0.10, 0.12, 0.15}, spacing = 0};

    -- Font/input resolution remains independent of platform font directories.
    fCheckpoint = function()
        if (tOptions.checkpoint) then tOptions.checkpoint(); end
        assert(not tOptions.cancelled or not tOptions.cancelled(), "PDF layout cancelled; no output was published.");
    end;
    fFont = function(tStyle)
        local sRole = tStyle.code and "code" or tStyle.bold and tStyle.italic and "boldItalic" or tStyle.bold and "bold" or tStyle.italic and "italic" or "regular";
        local tDescriptor = tStyle.font;
        local sKey;

        if (not tDescriptor and tOptions.resolveFont) then tDescriptor = tOptions.resolveFont(copy(tStyle)); end
        if (not tDescriptor and not tStyle.family) then tDescriptor = tOptions.fonts and tOptions.fonts[sRole]; end
        assert(tDescriptor and rawtype(tDescriptor.path) == "string", "PDF layout requires an explicit "..sRole.." font"..(tStyle.family and " for "..tStyle.family or "")..".");
        sKey = tDescriptor.path.."\0"..tostring(tDescriptor.face or 1);
        if (not tFontCache[sKey]) then tFontCache[sKey] = oDocument.addFont(tDescriptor.path, tDescriptor.face); end
        local tFont = tFontCache[sKey];
        if (not tFont.fallbacks and tOptions.resolveFallbackFonts) then
            tFont.fallbacks = {};
            for _, tFallback in ipairs(tOptions.resolveFallbackFonts()) do
                local sFallbackKey = tFallback.path.."\0"..tostring(tFallback.face or 1);
                if (sFallbackKey ~= sKey) then
                    if (not tFontCache[sFallbackKey]) then tFontCache[sFallbackKey] = oDocument.addFont(tFallback.path, tFallback.face); end
                    tFont.fallbacks[#tFont.fallbacks + 1] = tFontCache[sFallbackKey];
                end
            end
        end
        return tFont;
    end;
    fMetrics = function(tStyle, sText)
        local tFont = fFont(tStyle);
        local sKey = tFont.index.."/"..tStyle.size.."/"..(tStyle.spacing or 0).."/"..(tStyle.nativeStyle or "").."/"..sText;

        if (not tMeasureCache[sKey]) then
            local tMetrics = tOptions.measureStyledText and tStyle.nativeStyle and tOptions.measureStyledText(tStyle, sText);

            tMeasureCache[sKey] = tMetrics or {width = oDocument.measureText(tFont, tStyle.size, sText, tStyle.spacing),
                ascent = tFont.ascent * tStyle.size / 1000, descent = -tFont.descent * tStyle.size / 1000};
        end
        return tMeasureCache[sKey];
    end;
    fMeasure = function(tStyle, sText)
        return fMetrics(tStyle, sText).width;
    end;
    fLink = function(sTarget)
        local sFile, sAnchor = sTarget:match("^([^#]+)#(.+)$");

        if (sTarget:sub(1, 1) == "#" or sTarget:match("^[%a][%w+.-]*:")) then return sTarget; end
        if (sFile and tFileTargets[sFile]) then return "#"..sAnchor; end
        if (tFileTargets[sTarget]) then return "#"..tFileTargets[sTarget]; end
        error("PDF link does not resolve to a manual section or supported URI: "..sTarget);
    end;
    for _, tChapter in ipairs(tData.chapters) do
        local tSections = Document.sections({context = tData.context, chapters = {tChapter}});

        tFileTargets[tChapter.name] = tSections[1].id;
    end
    tRoot = parse(Document.build(tData, "pdf", tSettings));

    -- Flatten semantic inline nodes without reparsing Markdown or executable HTML.
    fInline = function(tNode, tStyle, tRuns, bLiteral, fCheckText)
        local tNext = copy(tStyle);
        local sTag = tNode.tag;

        if (fCheckText) then
            fCheckpoint();
            if (sTag == "script" or sTag == "style" or hasClass(tNode, "pdf-page-header") or hasClass(tNode, "heading-anchor")) then return; end
            local nHeading = tonumber(sTag:match("^h([1-6])$"));
            if (nHeading) then
                local tSizes = tOptions.headingSizes or {24, 20, 16, 14, 12, 11};
                tNext.size, tNext.bold = tSizes[nHeading] or tStyle.size, true;
            elseif (sTag == "pre") then tNext.code, bLiteral = true, true;
            elseif (sTag == "thead") then tNext.bold = true; end
            if ((sTag == "ul" or sTag == "ol") and not hasClass(tNode, "pdf-toc")) then
                local nItem = tonumber(tNode.attributes.start) or 1;
                for _, tItem in ipairs(tNode.children) do
                    if (tItem.tag == "li") then
                        fCheckText(sTag == "ol" and nItem.."." or "•", tStyle);
                        nItem = nItem + 1;
                    end
                end
            elseif (hasClass(tNode, "pdf-toc")) then fCheckText("0123456789", tStyle); end
        end
        if (sTag == "text") then
            local sText = bLiteral and tNode.text or tNode.text:gsub("%s+", " ");
            if (fCheckText) then
                if (sText:find("%S")) then fCheckText(sText:gsub("[\r\n]", ""):gsub("\t", "    "), tStyle); end
            else tRuns[#tRuns + 1] = {text = sText, style = tStyle}; end
            return;
        elseif (sTag == "br") then tRuns[#tRuns + 1] = {kind = "break"}; return;
        elseif (sTag == "img") then tRuns[#tRuns + 1] = {kind = "image", source = tNode.attributes.src, style = tStyle}; return; end
        if (tNode.attributes.id) then tRuns[#tRuns + 1] = {kind = "anchor", id = tNode.attributes.id}; end
        if (sTag == "strong") then tNext.bold = true;
        elseif (sTag == "em") then tNext.italic = true;
        elseif (sTag == "s") then tNext.strike = true;
        elseif (sTag == "code") then tNext.code = true;
        elseif (sTag == "a" and tNode.attributes.href) then
            tNext.link, tNext.underline = fLink(tNode.attributes.href), true;
            tNext.color = tOptions.linkColor or {0.05, 0.25, 0.50};
        elseif (sTag == "span" and tNode.attributes["data-font-style"]) then
            local sName = tNode.attributes["data-font-style"];
            local tCustom = tStyles[sName:lower()] or (tOptions.resolveStyle and tOptions.resolveStyle(sName));
            local tAllowed = {size = true, color = true, bold = true, italic = true, underline = true, strike = true, spacing = true, family = true, font = true, nativeStyle = true};

            assert(tCustom, "PDF style requires a native layout descriptor: "..sName);
            for sKey, vValue in pairs(tCustom) do
                assert(tAllowed[sKey], "Unsupported PDF style property: "..sName.."."..sKey);
                tNext[sKey] = vValue;
            end
        end
        for _, tChild in ipairs(tNode.children) do fInline(tChild, tNext, tRuns, bLiteral, fCheckText); end
    end;

    -- Wrapping produces measured lines; it never writes output while paginating.
    fWrap = function(tRuns, nAvailable, bLiteral)
        local tLines = {};
        local tLine = {pieces = {}, width = 0, ascent = 0, descent = 0, size = tBase.size};
        local fFlush;
        local fPiece;

        assert(nAvailable > 0, "PDF nesting leaves no text width.");
        fFlush = function(bForce)
            if (#tLine.pieces > 0 or bForce) then
                local tLast = tLine.pieces[#tLine.pieces];

                if (tLast and tLast.text and not bLiteral and tLast.text:match("%s+$")) then
                    local sTrimmed = tLast.text:gsub("%s+$", "");
                    local nTrimmed = fMeasure(tLast.style, sTrimmed);

                    tLine.width = tLine.width - tLast.width + nTrimmed;
                    tLast.text, tLast.width = sTrimmed, nTrimmed;
                end
                tLine.height = math.max(tLine.size * (tOptions.lineSpacing or 1.25), tLine.ascent + tLine.descent + 2);
                tLines[#tLines + 1] = tLine;
            end
            tLine = {pieces = {}, width = 0, ascent = 0, descent = 0, size = tBase.size};
        end;
        fPiece = function(sText, tStyle)
            local tMetrics = fMetrics(tStyle, sText);
            local nWidth = tMetrics.width;
            local tFont = fFont(tStyle);
            local tPrevious = tLine.pieces[#tLine.pieces];
            local nAdditional = nWidth;

            if (nWidth > nAvailable and not sText:match("^%s*$")) then
                assert(utf8.len(sText) > 1, "A glyph and its effects exceed the available PDF column width.");
                for _, nCode in utf8.codes(sText) do fPiece(utf8.char(nCode), tStyle); end
                return;
            end
            assert(nWidth <= nAvailable + 0.001, "A glyph exceeds the available PDF column width.");
            if (tPrevious and tPrevious.text and tPrevious.style == tStyle) then
                nAdditional = fMeasure(tStyle, tPrevious.text..sText) - tPrevious.width;
            end
            if (tLine.width + nAdditional > nAvailable + 0.001 and tLine.width > 0) then
                fFlush();
                tPrevious, nAdditional = nil, nWidth;
            end
            if (not bLiteral and tLine.width == 0 and sText:match("^%s*$")) then return; end
            if (tPrevious and tPrevious.text and tPrevious.style == tStyle) then
                tPrevious.text = tPrevious.text..sText;
                tPrevious.width = fMeasure(tStyle, tPrevious.text);
            else
                tLine.pieces[#tLine.pieces + 1] = {text = sText, style = tStyle, font = tFont, width = nWidth};
            end
            tLine.width = tLine.width + nAdditional;
            tLine.ascent = math.max(tLine.ascent, tMetrics.ascent);
            tLine.descent = math.max(tLine.descent, tMetrics.descent);
            tLine.size = math.max(tLine.size, tStyle.size);
        end;
        for _, tRun in ipairs(tRuns) do
            if (tRun.kind == "break") then fFlush(true);
            elseif (tRun.kind == "image") then fFlush(); tLines[#tLines + 1] = tRun;
            elseif (tRun.kind == "anchor") then tLine.pieces[#tLine.pieces + 1] = tRun;
            elseif (bLiteral) then
                local nStart = 1;

                while (nStart <= #tRun.text) do
                    local nBreak = tRun.text:find("\n", nStart, true);
                    local sPart = tRun.text:sub(nStart, nBreak and nBreak - 1 or -1):gsub("\t", "    ");

                    for _, nCode in utf8.codes(sPart) do fPiece(utf8.char(nCode), tRun.style); end
                    if (not nBreak) then break; end
                    fFlush(true);
                    nStart = nBreak + 1;
                end
            else
                do
                    local nStart = 1;

                    while (nStart <= #tRun.text) do
                        local nFirst, nLast = tRun.text:find("%s+", nStart);

                        if (not nFirst) then fPiece(tRun.text:sub(nStart), tRun.style); break; end
                        if (nFirst > nStart) then fPiece(tRun.text:sub(nStart, nFirst - 1), tRun.style); end
                        fPiece(" ", tRun.style);
                        nStart = nLast + 1;
                    end
                end
            end
        end
        fFlush();
        return tLines;
    end;
    fNewPage = function()
        fCheckpoint();
        nPage = nPage + 1;
        assert(nPage <= (tOptions.maxPages or 10000), "PDF exceeds the configured page limit.");
        tCurrent = {operations = {}, left = nPage % 2 == 1 and nInside or nOutside};
        tPagePlans[nPage] = tCurrent;
        nY = nTop;
        for _, sID in ipairs(tPendingAnchors) do
            local tDestination = tDestinations[sID];

            tDestination.page, tDestination.x, tDestination.y = nPage, tCurrent.left + tDestination.indent, nY;
        end
        if (tOptions.onProgress) then tOptions.onProgress("paginating", "Paginating page "..nPage, nPage); end
    end;
    fEnsure = function(nRequired)
        if (not tCurrent) then fNewPage(); end
        assert(nRequired <= nHeight - nTop - nBottom + 0.001, "A PDF layout item is taller than the content area.");
        if (nY + nRequired > nHeight - nBottom + 0.001) then fNewPage(); end
    end;
    fAnchor = function(sID, nIndent)
        assert(not tDestinations[sID], "Duplicate PDF layout destination: "..sID);
        tDestinations[sID] = {page = nPage, x = tCurrent.left + nIndent, y = nY, indent = nIndent};
        tPendingAnchors[#tPendingAnchors + 1] = sID;
    end;
    fLine = function(tLine, nIndent, nAvailable, sAlign)
        local nX = tCurrent.left + nIndent;
        local nOffset = sAlign == "right" and nAvailable - tLine.width or sAlign == "center" and (nAvailable - tLine.width) / 2 or 0;

        if (tPendingMarker) then
            local tStyle = tPendingMarker.style;

            tCurrent.operations[#tCurrent.operations + 1] = {kind = "text", x = tCurrent.left + tPendingMarker.indent,
                y = nY + tLine.ascent, top = nY, height = tLine.height,
                piece = {text = tPendingMarker.text, style = tStyle, font = fFont(tStyle), width = fMeasure(tStyle, tPendingMarker.text)}};
            tPendingMarker = nil;
        end
        for _, tPiece in ipairs(tLine.pieces) do
            if (tPiece.kind == "anchor") then
                if (not tLine.repeatAnchors or not tDestinations[tPiece.id]) then fAnchor(tPiece.id, nIndent); end
            elseif (tPiece.text ~= "") then
                tCurrent.operations[#tCurrent.operations + 1] = {kind = "text", x = nX + nOffset, y = nY + tLine.ascent,
                    top = nY, height = tLine.height, piece = tPiece};
                nX = nX + tPiece.width;
            end
        end
        nY = nY + tLine.height;
        tPendingAnchors = {};
    end;
    fImageData = function(sSource, nAvailable, nMaxHeight)
        local sRelative = assert(sSource:match("^content%-images/(.+)$"), "PDF images must be saved in the manual Images folder: "..sSource);
        local tImage;
        local nDisplayWidth, nDisplayHeight;
        local nScale;

        sRelative = sRelative:gsub("%%(%x%x)", function(sHex) return string.char(tonumber(sHex, 16)); end);
        assert(not sRelative:find("[%z\1-\31\\]") and not sRelative:match("^/") and not ("/"..sRelative.."/"):find("/../", 1, true), "Invalid PDF image path.");
        if (not tImageCache[sRelative]) then tImageCache[sRelative] = oDocument.addImage(tData.context.manualRoot.."/Images/"..sRelative); end
        tImage = tImageCache[sRelative];
        nDisplayWidth = tImage.width * 72 / (tOptions.imageDPI or 96);
        nDisplayHeight = tImage.height * 72 / (tOptions.imageDPI or 96);
        nScale = math.min(1, nAvailable / nDisplayWidth, (nMaxHeight or nHeight - nTop - nBottom) / nDisplayHeight);
        return tImage, nDisplayWidth * nScale, nDisplayHeight * nScale;
    end;
    fImage = function(sSource, nIndent, nAvailable, tStyle)
        local tImage, nDisplayWidth, nDisplayHeight = fImageData(sSource, nAvailable);

        fEnsure(nDisplayHeight);
        tCurrent.operations[#tCurrent.operations + 1] = {kind = "image", image = tImage, x = tCurrent.left + nIndent + (nAvailable - nDisplayWidth) / 2,
            y = nY, width = nDisplayWidth, height = nDisplayHeight, link = tStyle and tStyle.link};
        nY = nY + nDisplayHeight;
        tPendingAnchors = {};
    end;
    fParagraph = function(tNode, tStyle, nIndent, nAvailable, tPolicy)
        local tRuns = {};
        local tLines;
        local nIndex = 1;
        local nAfter;

        tPolicy = tPolicy or {};
        fCheckpoint();
        fInline(tNode, tStyle, tRuns, tPolicy.literal);
        tLines = fWrap(tRuns, nAvailable, tPolicy.literal);
        if (#tLines == 0) then return; end
        nAfter = tPolicy.after or tOptions.paragraphSpacing or tBase.size * 0.6;
        if (tPolicy.heading and #tLines > 0) then
            local nHeadingHeight = 0;

            for _, tLine in ipairs(tLines) do
                assert(not tLine.kind, "Heading images are not supported in PDF layout.");
                nHeadingHeight = nHeadingHeight + tLine.height;
            end
            fEnsure(math.min(nHeight - nTop - nBottom, nHeadingHeight + nAfter + tBase.size * 2.5));
        end
        while (nIndex <= #tLines) do
            fCheckpoint();
            local tLine = tLines[nIndex];

            if (tLine.kind == "image") then
                fImage(tLine.source, nIndent, nAvailable, tLine.style);
                nIndex = nIndex + 1;
            else
                local nFit, nUsed = 0, 0;

                fEnsure(tLine.height);
                while (tLines[nIndex + nFit] and not tLines[nIndex + nFit].kind
                    and nY + nUsed + tLines[nIndex + nFit].height <= nHeight - nBottom + 0.001) do
                    nUsed = nUsed + tLines[nIndex + nFit].height;
                    nFit = nFit + 1;
                end
                assert(nFit > 0, "PDF paragraph line cannot fit on an empty page.");
                if (nFit == 1 and #tLines - nIndex >= 1 and nY > nTop) then fNewPage();
                else
                    if (#tLines - nIndex + 1 - nFit == 1 and nFit > 1) then nFit = nFit - 1; end
                    for _ = 1, nFit do
                        if (tPolicy.background) then
                            tCurrent.operations[#tCurrent.operations + 1] = {kind = "rectangle", x = tCurrent.left + nIndent, y = nY,
                                width = nAvailable, height = tLines[nIndex].height, color = tPolicy.background};
                        end
                        fLine(tLines[nIndex], nIndent, nAvailable, tPolicy.align);
                        nIndex = nIndex + 1;
                    end
                    if (nIndex <= #tLines and not tLines[nIndex].kind) then fNewPage(); end
                end
            end
        end
        nY = math.min(nHeight - nBottom, nY + nAfter);
    end;

    -- Table cells are measured once; page fragments consume each line exactly once.
    fTable = function(tNode, tStyle, nIndent, nAvailable)
        local tRows = {};
        local tHeaders = {};
        local nColumns = 0;
        local fRows;
        local fDrawRow;
        local nColumnWidth;
        local nHeaderHeight = 0;

        fRows = function(tContainer, bHeader)
            for _, tChild in ipairs(tContainer.children) do
                if (tChild.tag == "thead") then fRows(tChild, true);
                elseif (tChild.tag == "tbody") then fRows(tChild, false);
                elseif (tChild.tag == "tr") then
                    local tRow = {cells = {}, header = bHeader};

                    for _, tCell in ipairs(tChild.children) do
                        if (tCell.tag == "th" or tCell.tag == "td") then tRow.cells[#tRow.cells + 1] = tCell; end
                    end
                    nColumns = math.max(nColumns, #tRow.cells);
                    tRows[#tRows + 1] = tRow;
                end
            end
        end;
        fRows(tNode, false);
        assert(nColumns > 0 and nColumns <= (tOptions.maxTableColumns or 32), "Invalid PDF table column count.");
        nColumnWidth = nAvailable / nColumns;
        for _, tRow in ipairs(tRows) do
            tRow.lines, tRow.count, tRow.heights, tRow.ascents = {}, 0, {}, {};
            for nColumn = 1, nColumns do
                local tRuns = {};
                local tCellStyle = copy(tStyle);
                local tCell = tRow.cells[nColumn];

                tCellStyle.bold = tRow.header or tCellStyle.bold;
                if (tCell) then fInline(tCell, tCellStyle, tRuns); end
                tRow.lines[nColumn] = fWrap(tRuns, nColumnWidth - 10);
                tRow.count = math.max(tRow.count, #tRow.lines[nColumn]);
                for nLine, tLine in ipairs(tRow.lines[nColumn]) do
                    if (tLine.kind == "image") then
                        tLine.image, tLine.width, tLine.height = fImageData(tLine.source, nColumnWidth - 10, (nHeight - nTop - nBottom) / 3);
                        tLine.ascent = 0;
                    end
                    tRow.heights[nLine] = math.max(tRow.heights[nLine] or 0, tLine.height);
                    tRow.ascents[nLine] = math.max(tRow.ascents[nLine] or 0, tLine.ascent);
                end
            end
            tRow.count = math.max(1, tRow.count);
            for nLine = 1, tRow.count do
                tRow.heights[nLine] = tRow.heights[nLine] or tBase.size * (tOptions.lineSpacing or 1.25);
                tRow.ascents[nLine] = tRow.ascents[nLine] or 0;
            end
            if (tRow.header) then
                tHeaders[#tHeaders + 1] = tRow;
                nHeaderHeight = nHeaderHeight + 10;
                for _, nLineHeight in ipairs(tRow.heights) do nHeaderHeight = nHeaderHeight + nLineHeight; end
            end
        end
        assert(nHeaderHeight < (nHeight - nTop - nBottom) / 2, "PDF table header is too tall to repeat safely.");
        fDrawRow = function(tRow, nFirst, nCount, bRepeat)
            local nStartY = nY;
            local nRowHeight = 10;
            local nStartX = tCurrent.left + nIndent;

            for nLine = nFirst, nFirst + nCount - 1 do nRowHeight = nRowHeight + tRow.heights[nLine]; end
            tCurrent.operations[#tCurrent.operations + 1] = {kind = "rectangle", x = nStartX, y = nStartY, width = nAvailable,
                height = nRowHeight, color = tRow.header and (tOptions.tableHeaderColor or {0.90, 0.92, 0.94}) or {1, 1, 1}};
            for nColumn = 1, nColumns do
                local tCell = tRow.cells[nColumn];
                local sAlign = tCell and (tCell.attributes.style or ""):match("text%-align:(%a+)");
                local nLineOffset = 0;

                for nLine = nFirst, nFirst + nCount - 1 do
                    local tLine = tRow.lines[nColumn][nLine];

                    if (tLine) then
                        local tCopy = copy(tLine);

                        tCopy.ascent, tCopy.height, tCopy.repeatAnchors = tRow.ascents[nLine], tRow.heights[nLine], bRepeat;
                        nY = nStartY + 5 + nLineOffset;
                        if (tLine.kind == "image") then
                            tCurrent.operations[#tCurrent.operations + 1] = {kind = "image", image = tLine.image,
                                x = nStartX + (nColumn - 1) * nColumnWidth + (nColumnWidth - tLine.width) / 2,
                                y = nY, width = tLine.width, height = tLine.height, link = tLine.style and tLine.style.link};
                        else
                            fLine(tCopy, nIndent + (nColumn - 1) * nColumnWidth + 5, nColumnWidth - 10, sAlign);
                        end
                    end
                    nLineOffset = nLineOffset + tRow.heights[nLine];
                end
                tCurrent.operations[#tCurrent.operations + 1] = {kind = "rectangle", x = nStartX + (nColumn - 1) * nColumnWidth,
                    y = nStartY, width = 0.4, height = nRowHeight, color = {0.65, 0.69, 0.73}};
            end
            tCurrent.operations[#tCurrent.operations + 1] = {kind = "rectangle", x = nStartX + nAvailable - 0.4,
                y = nStartY, width = 0.4, height = nRowHeight, color = {0.65, 0.69, 0.73}};
            for _, nBorderY in ipairs({nStartY, nStartY + nRowHeight - 0.4}) do
                tCurrent.operations[#tCurrent.operations + 1] = {kind = "rectangle", x = nStartX, y = nBorderY,
                    width = nAvailable, height = 0.4, color = {0.65, 0.69, 0.73}};
            end
            nY = nStartY + nRowHeight;
        end;
        if (#tRows > #tHeaders) then fEnsure(nHeaderHeight + tRows[#tHeaders + 1].heights[1] + 10); end
        for _, tRow in ipairs(tRows) do
            local nFirst = 1;

            while (nFirst <= tRow.count) do
                local nFit, nUsed = 0, 10;
                local fFit;

                fFit = function()
                    nFit, nUsed = 0, 10;
                    while (tRow.heights[nFirst + nFit] and nY + nUsed + tRow.heights[nFirst + nFit] <= nHeight - nBottom + 0.001) do
                        nUsed = nUsed + tRow.heights[nFirst + nFit];
                        nFit = nFit + 1;
                    end
                end;
                fCheckpoint();
                fFit();
                if (nFit < 1) then
                    fNewPage();
                    if (not tRow.header) then for _, tHeader in ipairs(tHeaders) do fDrawRow(tHeader, 1, tHeader.count, true); end end
                    fFit();
                end
                assert(nFit > 0, "PDF table row cannot fit below its repeated header.");
                fDrawRow(tRow, nFirst, nFit);
                nFirst = nFirst + nFit;
            end
        end
        nY = math.min(nHeight - nBottom, nY + (tOptions.paragraphSpacing or tBase.size * 0.6));
    end;

    -- Block walking preserves the renderer's canonical cover/contents/quicksheets.
    fWalk = function(tNode, tStyle, nIndent, nAvailable)
        local sTag = tNode.tag;
        local nHeading = tonumber(sTag:match("^h([1-6])$"));

        fCheckpoint();
        if (sTag == "script" or sTag == "style" or hasClass(tNode, "pdf-page-header") or hasClass(tNode, "heading-anchor")) then return; end
        if (sTag == "text") then
            assert(not tNode.text:find("%S"), "Unexpected uncontained PDF block text.");
            return;
        end
        if (hasClass(tNode, "pdf-contents") or hasClass(tNode, "pdf-cover") or (sTag == "section" and tNode.attributes["data-chapter"])) then
            if (tCurrent and #tCurrent.operations > 0) then fNewPage(); end
        end
        if (hasClass(tNode, "pdf-cover")) then
            local tIntro = Document.sections(tData)[1];

            fAnchor(tIntro.id, nIndent);
            tHeadings[#tHeadings + 1] = {title = tIntro.title, id = tIntro.id, level = tIntro.level};
        end
        if (tNode.attributes.id) then
            fEnsure(tBase.size * 4);
            fAnchor(tNode.attributes.id, nIndent);
        end
        if (nHeading) then
            local tHeading = copy(tStyle);
            local tSizes = tOptions.headingSizes or {24, 20, 16, 14, 12, 11};

            tHeading.size, tHeading.bold = tSizes[nHeading] or tStyle.size, true;
            nY = math.min(nHeight - nBottom, nY + (nY > nTop and tHeading.size * 0.35 or 0));
            fParagraph(tNode, tHeading, nIndent, nAvailable, {heading = true, after = tHeading.size * 0.35});
        elseif (sTag == "p") then fParagraph(tNode, tStyle, nIndent, nAvailable);
        elseif (sTag == "pre") then
            local tCode = copy(tStyle);

            tCode.code = true;
            fParagraph(tNode, tCode, nIndent + 6, nAvailable - 12, {literal = true, background = tOptions.codeBackground or {0.95, 0.96, 0.97}});
        elseif (sTag == "blockquote") then
            for _, tChild in ipairs(tNode.children) do fWalk(tChild, tStyle, nIndent + 14, nAvailable - 28); end
        elseif (sTag == "table") then fTable(tNode, tStyle, nIndent, nAvailable);
        elseif (sTag == "ul" or sTag == "ol") then
            local nItem = tonumber(tNode.attributes.start) or 1;

            if (hasClass(tNode, "pdf-toc")) then
                for _, tItem in ipairs(tNode.children) do
                    if (tItem.tag == "li") then
                        local tLink;
                        local nLevel = tonumber(tItem.attributes["data-level"]) or 2;
                        local nInset = math.max(0, nLevel - 2) * 10;
                        local tLabel;
                        local nEntryPage, nEntryY;

                        for _, tChild in ipairs(tItem.children) do if (tChild.tag == "a") then tLink = tChild; break; end end
                        assert(tLink, "PDF contents entry has no destination.");
                        fEnsure(tStyle.size * 2.5);
                        nEntryPage, nEntryY = nPage, nY;
                        tLabel = {tag = "p", attributes = {}, children = {tLink}};
                        fParagraph(tLabel, tStyle, nIndent + nInset, nAvailable - nInset - 36, {after = tStyle.size * 0.25});
                        do
                            local sTarget = fLink(tLink.attributes.href);
                            local tFirstLine;
                            local nLabelPage;

                            for nScanPage = nEntryPage, nPage do
                                for _, tOperation in ipairs(tPagePlans[nScanPage].operations) do
                                    if (tOperation.kind == "text" and tOperation.piece.style.link == sTarget
                                        and (nScanPage > nEntryPage or tOperation.top >= nEntryY)) then
                                        tFirstLine, nLabelPage = tOperation, nScanPage;
                                        break;
                                    end
                                end
                                if (tFirstLine) then break; end
                            end
                            assert(tFirstLine, "PDF contents entry has no visible label.");
                            tPagePlans[nLabelPage].operations[#tPagePlans[nLabelPage].operations + 1] = {kind = "contentsNumber", target = sTarget:sub(2),
                                x = tPagePlans[nLabelPage].left + nIndent + nAvailable - 30, y = tFirstLine.top, style = tStyle};
                        end
                    end
                end
            else
                for _, tItem in ipairs(tNode.children) do
                    if (tItem.tag == "li") then
                        local tInline = {tag = "p", attributes = {}, children = {}};
                        local sMarker = sTag == "ol" and nItem.."." or "•";
                        local fFlush;
                        local nGutter = math.max(20, fMeasure(tStyle, sMarker) + 6);

                        fEnsure(tStyle.size * 2.5);
                        assert(not tPendingMarker, "A PDF list marker has no item content.");
                        tPendingMarker = {text = sMarker, style = tStyle, indent = nIndent};
                        fFlush = function()
                            if (#tInline.children > 0) then fParagraph(tInline, tStyle, nIndent + nGutter, nAvailable - nGutter); tInline.children = {}; end
                        end;
                        for _, tChild in ipairs(tItem.children) do
                            if (tChild.tag == "ul" or tChild.tag == "ol" or tChild.tag == "p" or tChild.tag == "pre" or tChild.tag == "blockquote") then
                                fFlush();
                                if (tPendingMarker and (tChild.tag == "ul" or tChild.tag == "ol")) then
                                    local tFont = fFont(tStyle);
                                    local tEmpty = {pieces = {}, width = 0, size = tStyle.size,
                                        ascent = tFont.ascent * tStyle.size / 1000, height = tStyle.size * (tOptions.lineSpacing or 1.25)};

                                    fEnsure(tEmpty.height);
                                    fLine(tEmpty, nIndent + nGutter, nAvailable - nGutter);
                                end
                                fWalk(tChild, tStyle, nIndent + nGutter, nAvailable - nGutter);
                            else tInline.children[#tInline.children + 1] = tChild; end
                        end
                        fFlush();
                        if (tPendingMarker) then
                            local tFont = fFont(tStyle);
                            local tEmpty = {pieces = {}, width = 0, size = tStyle.size,
                                ascent = tFont.ascent * tStyle.size / 1000, height = tStyle.size * (tOptions.lineSpacing or 1.25)};

                            fEnsure(tEmpty.height);
                            fLine(tEmpty, nIndent + nGutter, nAvailable - nGutter);
                        end
                        nItem = nItem + 1;
                    end
                end
            end
        elseif (sTag == "hr") then
            fEnsure(10);
            tCurrent.operations[#tCurrent.operations + 1] = {kind = "rectangle", x = tCurrent.left + nIndent, y = nY + 4,
                width = nAvailable, height = 0.6, color = {0.65, 0.69, 0.73}};
            nY = nY + 10;
        elseif (sTag == "img") then fImage(tNode.attributes.src, nIndent, nAvailable);
        elseif (sTag == "body" or sTag == "main" or sTag == "section" or sTag == "div") then
            if (sTag == "section" and tNode.attributes.id) then
                local sTitle;
                local nLevel = tonumber((tNode.attributes and tNode.attributes.class or ""):match("section%-level%-(%d+)")) or 2;

                for _, tChild in ipairs(tNode.children) do
                    if (hasClass(tChild, "section-heading")) then sTitle = plain(tChild):gsub("%s+", " "); break; end
                end
                if (sTitle) then tHeadings[#tHeadings + 1] = {title = sTitle, id = tNode.attributes.id, level = nLevel}; end
            end
            for _, tChild in ipairs(tNode.children) do fWalk(tChild, tStyle, nIndent, nAvailable); end
        else error("Unsupported PDF block element: "..sTag); end
    end;

    -- Validate the exact resolved faces before measuring, paginating, or drawing.
    if (tOptions.onProgress) then tOptions.onProgress("fonts", "Checking manual text for missing font glyphs."); end
    local tChecked, tMissing = {}, {};
    local function checkText(sText, tStyle)
        local tFont = fFont(tStyle);
        local tSeen = tChecked[tFont];
        if (not tSeen) then tSeen = {}; tChecked[tFont] = tSeen; end
        local tCharacters = {};
        for _, nCode in utf8.codes(sText) do
            if (not tSeen[nCode]) then
                tSeen[nCode] = true;
                tCharacters[#tCharacters + 1] = utf8.char(nCode);
            end
        end
        for _, nCode in ipairs(oDocument.missingGlyphs(tFont, table.concat(tCharacters))) do
            tMissing[#tMissing + 1] = string.format("%s — U+%04X (%s), style %s, file %s",
                tFont.name, nCode, utf8.char(nCode), tStyle.nativeStyle or tStyle.family or (tStyle.code and "code" or "body"),
                tFont.path);
        end
    end
    fInline(tRoot, tBase, {}, false, checkText);
    if (tOptions.showHeader ~= false and nTop - nBleed >= (tOptions.headerSize or 8) * 2) then
        local tHeader = copy(tBase);
        tHeader.size = tOptions.headerSize or 8;
        checkText(tData.context.gameName.." / RULEBOOK", tHeader);
    end
    if (tOptions.showFooter ~= false and nBottom - nBleed >= (tOptions.footerSize or 8) * 2) then
        local tFooter = copy(tBase);
        tFooter.size = tOptions.footerSize or 8;
        checkText("0123456789", tFooter);
    end
    assert(#tMissing == 0, "PDF font preflight failed before pagination/rendering:\n"..table.concat(tMissing, "\n"));
    if (tOptions.onProgress) then tOptions.onProgress("paginating", "Font preflight passed. Paginating manual content."); end

    fNewPage();
    fWalk(tRoot, tBase, 0, nContentWidth);
    fCheckpoint();

    -- Resolve forward targets only after pagination has assigned all page numbers.
    for _, tHeading in ipairs(tHeadings) do
        assert(tDestinations[tHeading.id], "PDF heading has no destination: "..tHeading.id);
        oDocument.outline(tHeading.title, tHeading.id, tHeading.level);
    end
    for nIndex, tPlan in ipairs(tPagePlans) do
        local tPage = oDocument.addPage(nWidth, nHeight);

        oDocument.setPageBoxes(tPage, {nBleed, nBleed, nWidth - nBleed, nHeight - nBleed});
        tPlan.page = tPage;
        if (tOptions.decoratePage) then tOptions.decoratePage(oDocument, tPage, nIndex, #tPagePlans, "background"); end
        if (tOptions.showHeader ~= false and nTop - nBleed >= (tOptions.headerSize or 8) * 2) then
            local tHeader = copy(tBase);
            local sHeader = tData.context.gameName.." / RULEBOOK";

            tHeader.size = tOptions.headerSize or 8;
            assert(fMeasure(tHeader, sHeader) <= nContentWidth, "PDF header is too wide; choose a smaller header size or disable it.");
            oDocument.text(tPage, fFont(tHeader), tHeader.size, tPlan.left, nBleed + tHeader.size * 1.5, sHeader, tHeader);
        end
        if (tOptions.showFooter ~= false and nBottom - nBleed >= (tOptions.footerSize or 8) * 2) then
            local tFooter = copy(tBase);
            local sNumber = tostring(nIndex);
            local nX;

            tFooter.size = tOptions.footerSize or 8;
            nX = nIndex % 2 == 1 and nWidth - nOutside - fMeasure(tFooter, sNumber) or nOutside;
            oDocument.text(tPage, fFont(tFooter), tFooter.size, nX, nHeight - nBleed - tFooter.size, sNumber, tFooter);
        end
    end
    for sID, tDestination in pairs(tDestinations) do
        oDocument.destination(sID, tPagePlans[tDestination.page].page, tDestination.x, tDestination.y);
    end
    for nIndex, tPlan in ipairs(tPagePlans) do
        local tPage = tPlan.page;

        fCheckpoint();
        for nOperation, tOperation in ipairs(tPlan.operations) do
            if (nOperation % 64 == 0) then fCheckpoint(); end
            if (tOperation.kind == "rectangle") then
                oDocument.rectangle(tPage, tOperation.x, tOperation.y, tOperation.width, tOperation.height, tOperation.color);
            elseif (tOperation.kind == "image") then
                oDocument.image(tPage, tOperation.image, tOperation.x, tOperation.y, tOperation.width, tOperation.height);
                if (tOperation.link) then oDocument.link(tPage, tOperation.x, tOperation.y, tOperation.width, tOperation.height, tOperation.link); end
            elseif (tOperation.kind == "contentsNumber") then
                local tDestination = assert(tDestinations[tOperation.target], "Unresolved PDF contents entry: "..tOperation.target);
                local sNumber = tostring(tDestination.page);
                local tStyle = tOperation.style;
                local nTextWidth = fMeasure(tStyle, sNumber);
                local nBaseline = tOperation.y + fFont(tStyle).ascent * tStyle.size / 1000;

                assert(nTextWidth <= 30, "PDF contents page number exceeds its reserved column.");
                oDocument.text(tPage, fFont(tStyle), tStyle.size, tOperation.x + 30 - nTextWidth, nBaseline, sNumber, tStyle);
                oDocument.link(tPage, tOperation.x, tOperation.y, 30, tStyle.size * 1.25, "#"..tOperation.target);
            elseif (tOperation.kind == "text") then
                local tPiece = tOperation.piece;
                local tStyle = tPiece.style;

                local bStyled = tOptions.drawStyledText and tStyle.nativeStyle and tOptions.drawStyledText(oDocument, tPage, tOperation);

                if (not bStyled) then oDocument.text(tPage, tPiece.font, tStyle.size, tOperation.x, tOperation.y, tPiece.text, tStyle); end
                if (tPiece.width > 0) then
                    if (tStyle.link) then oDocument.link(tPage, tOperation.x, tOperation.top, tPiece.width, tOperation.height, tStyle.link); end
                    if (not bStyled and (tStyle.underline or tStyle.strike)) then
                        if (tStyle.underline) then
                            oDocument.rectangle(tPage, tOperation.x, tOperation.y + tStyle.size * 0.08, tPiece.width, math.max(0.4, tStyle.size / 18), tStyle.color);
                        end
                        if (tStyle.strike) then
                            oDocument.rectangle(tPage, tOperation.x, tOperation.y - tStyle.size * 0.3, tPiece.width, math.max(0.4, tStyle.size / 18), tStyle.color);
                        end
                    end
                end
            end
        end
        if (tOptions.decoratePage) then tOptions.decoratePage(oDocument, tPage, nIndex, #tPagePlans, "foreground"); end
        if (tOptions.onProgress) then tOptions.onProgress("rendering", "Rendered page "..nIndex.." of "..#tPagePlans, nIndex); end
    end

    return {document = oDocument, pageCount = #tPagePlans, destinations = tDestinations, headings = tHeadings, pages = tPagePlans,
        options = tOptions, settings = tSettings, title = tData.context.gameName, baseFont = fFont(tBase), dispose = tOptions.dispose};
end

return PDFLayout;
