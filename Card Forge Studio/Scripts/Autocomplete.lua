-- Generated completion snapshots contain names and types only, never game values.
local wx = require("wx");
local Autocomplete = {};
local tHeaders = {};
local bDirty = true;
local bActive = false;
local tControls = setmetatable({}, {__mode = "k"});

local function hex(sText)
    return (sText:gsub(".", function(sChar) return string.format("%02X", sChar:byte()); end));
end

local function unhex(sText)
    return (sText:gsub("%x%x", function(sByte) return string.char(tonumber(sByte, 16)); end));
end

function Autocomplete.Path(sPrefix, sKey)
    if (sKey:find("[%c]")) then return nil; end
    local bIdentifier = sKey:match("^[%a_][%w_]*$") and not (" and break do else elseif end false for function goto if in local nil not or repeat return then true until while "):find(" "..sKey.." ", 1, true);
    if (sPrefix == "") then return bIdentifier and sKey or nil; end
    return bIdentifier and (sPrefix.."."..sKey) or (sPrefix.."["..string.format("%q", sKey).."]");
end

function Autocomplete.MarkDirty()
    bDirty = true;
end

function Autocomplete.SetHeaders(tInput)
    tHeaders = {};
    for nIndex, sHeader in ipairs(tInput or {}) do tHeaders[nIndex] = sHeader; end
    bDirty = true;
end

function Autocomplete.SetActive(bValue)
    bActive = bValue;
    Autocomplete.SetHeaders({});
end

function Autocomplete.Flush()
    if (not bDirty or not bActive or not UserEnv or not FS.Game.Root) then return; end
    local bOK, sError = xpcall(function()
        local tItems = UserEnv.GetCompletionEntries();
        if (#tHeaders > 0) then tItems[#tItems + 1] = {name = "_tRow", kind = "table"}; end
        for _, sHeader in ipairs(tHeaders) do
            local sName = Autocomplete.Path("_tRow", sHeader);
            if (sName) then tItems[#tItems + 1] = {name = sName, kind = "string"}; end
        end
        if (UserEnv.Get().STYLE == STYLE and STYLE and INIFile) then
            for _, sSection in ipairs(INIFile.GetSectionNames(FS.GetResourceRoot().."/Styles.ini")) do
                local sName = Autocomplete.Path("STYLE", sSection:upper());
                if (sName) then tItems[#tItems + 1] = {name = sName, kind = "table"}; end
            end
        end
        table.sort(tItems, function(a, b) return a.name < b.name; end);
        local tLines = {
            "-- Generated by Card Forge Studio. Names and types only.",
            "-- Sources: built-in UserEnv; game CFG and its imports; game ENV and its imports;",
            "-- processing-injected globals; active card-set headers; resource Styles.ini.",
            "return {version = 1, items = {",
        };
        local tSeen = {};
        for _, tItem in ipairs(tItems) do
            if (not tSeen[tItem.name]) then
                tSeen[tItem.name] = true;
                tLines[#tLines + 1] = '    {nameHex = "'..hex(tItem.name)..'", kind = "'..tItem.kind..'"},';
            end
        end
        tLines[#tLines + 1] = "}};";
        local sContent = table.concat(tLines, "\r\n").."\r\n";
        local pTarget = FS.Game.Root.."/autocomplete.lua";
        local hOld = io.open(pTarget, "rb");
        local sOld;
        if (hOld) then sOld = hOld:read("a"); hOld:close(); end
        if (sOld ~= sContent) then
            local oTemp = wx.wxFile();
            local pTemp = wx.wxFileName.CreateTempFileName(pTarget..".", oTemp);
            oTemp:Close(); oTemp:delete();
            local bWritten, sWriteError = pcall(function()
                local hFile = assert(io.open(pTemp, "wb"));
                local bWrite, sFailure = hFile:write(sContent);
                local bClose, sCloseError = hFile:close();
                assert(bWrite, sFailure); assert(bClose, sCloseError);
                assert(wx.wxRenameFile(pTemp, pTarget, true), "Cannot replace autocomplete snapshot.");
            end);
            if (not bWritten) then wx.wxRemoveFile(pTemp); error(sWriteError); end
        end
        for _, fDismiss in pairs(tControls) do fDismiss(); end
        bDirty = false;
    end, debug.traceback);
    if (not bOK) then Log.Error("Autocomplete: "..sError); end
end

function Autocomplete.Read()
    if (not bActive or not FS.Game.Root) then return {}; end
    local hFile = io.open(FS.Game.Root.."/autocomplete.lua", "rb");
    if (not hFile) then return {}; end
    local sText = hFile:read("a"); hFile:close();
    local tItems = {};
    -- Parse only generated data records; cached Lua is never executed.
    if (not sText:find("return {version = 1, items = {", 1, true)) then return tItems; end
    for sName, sKind in sText:gmatch('{nameHex = "([%x]+)", kind = "([%a]+)"}') do
        if (#sName % 2 == 0) then tItems[#tItems + 1] = {name = unhex(sName), kind = sKind}; end
    end
    return tItems;
end

local function documentation()
    local tDocs, tNames = {}, {};
    local tPaths = {_Scripts.."/Globals/UserEnv.lua", _Scripts.."/Forge.lua"};
    if (FS.Game.Root and FS.Game.Root ~= "") then
        local pRoot = FS.GetResourceRoot();
        tPaths[#tPaths + 1] = pRoot.."/Scripts/ENV.lua";
        tPaths[#tPaths + 1] = pRoot.."/Scripts/CFG.lua";
    end
    for _, pPath in ipairs(tPaths) do
        local hFile = io.open(pPath, "rb");
        if (hFile) then
            local sSource = hFile:read("a"); hFile:close();
            for sBlock in sSource:gmatch("%-%-%[%[!(.-)!%]%]") do
                local sFQXN = sBlock:match("@fqxn%s+([^%s]+)");
                if (sFQXN) then
                    local sDescription = sBlock:match("@desc%s+(.-)%s*@") or sBlock:match("@desc%s+(.+)") or "";
                    sDescription = sDescription:gsub("<[^>]*>", " "):gsub("&nbsp;", " "):gsub("&amp;", "&"):gsub("%s+", " ");
                    local tParameters = {};
                    for sName in sBlock:gmatch("@param%s+[^%s]+%s+([^%s]+)") do tParameters[#tParameters + 1] = sName; end
                    local tDoc = {description = sDescription, parameters = tParameters, inherit = sBlock:match("@inheritdoc%s+([^%s]+)")};
                    tDocs[sFQXN] = tDoc;
                    local sName = sBlock:match("@pulsarlua%s+[^%s]+%s+([^%s]+)");
                    if (not sName and sFQXN:sub(1, 12) == "CFS.UserEnv.") then
                        sName = sFQXN:sub(13):gsub("Namespaces%.", ""):gsub("Functions%.", ""):gsub("Constants%.", "");
                    end
                    if (sName) then tNames[sName] = tDoc; end
                end
            end
        end
    end
    for _, tDoc in pairs(tNames) do
        if (tDoc.inherit and tDocs[tDoc.inherit]) then
            tDoc.description = tDocs[tDoc.inherit].description;
            tDoc.parameters = tDocs[tDoc.inherit].parameters;
        end
    end
    return tNames;
end

function Autocomplete.Documentation()
    return documentation();
end

function Autocomplete.Describe(tItem, tDocs)
    local tDoc = tDocs[tItem.name];
    local sText = tItem.name.."  ("..tItem.kind..")";
    if (tDoc) then
        if (#tDoc.parameters > 0) then sText = tItem.name.."("..table.concat(tDoc.parameters, ", ")..")"; end
        return sText.."\n\n"..tDoc.description;
    end
    if (tItem.name:match("^_tRow[%.%[]") or tItem.name:match("^tRow[%.%[]")) then
        return sText.."\n\nA column from the currently loaded card set.";
    end
    return sText.."\n\nAvailable in the current user environment. No description is supplied for this entry.";
end

function Autocomplete.Style(oControl, sPrefix)
    local tSettings = require("Windows.EditorSettings").get();
    local function color(nColor)
        return wx.wxColour(math.floor(nColor / 65536), math.floor(nColor / 256) % 256, nColor % 256);
    end
    if (tSettings.autocompleteUseEditorTheme) then
        local tTheme = require("Windows.EditorSettings").themes()[tSettings.theme + 1];
        oControl:SetBackgroundColour(wx.wxColour(tTheme.colors[1]));
        oControl:SetForegroundColour(wx.wxColour(tTheme.colors[2]));
    else
        oControl:SetBackgroundColour(color(tSettings[sPrefix.."Background"]));
        oControl:SetForegroundColour(color(tSettings[sPrefix.."Text"]));
    end
    local nFontSize = tSettings.autocompleteUseEditorFontSize and tSettings.size or tSettings[sPrefix.."FontSize"];
    oControl:SetFont(wx.wxFont(nFontSize, wx.wxFONTFAMILY_MODERN, wx.wxFONTSTYLE_NORMAL, wx.wxFONTWEIGHT_NORMAL));
    oControl:Refresh();
end

function Autocomplete.Attach(oCode, bRowProcessor)
    local dPanel = wx.wxPanel(oCode, wx.wxID_ANY, wx.wxDefaultPosition, wx.wxSize(460, 300), wx.wxBORDER_SIMPLE);
    local oList = wx.wxListBox(dPanel, wx.wxID_ANY);
    local oHelp = wx.wxTextCtrl(dPanel, wx.wxID_ANY, "", wx.wxDefaultPosition, wx.wxDefaultSize, wx.wxTE_MULTILINE + wx.wxTE_READONLY);
    local oLayout = wx.wxBoxSizer(wx.wxVERTICAL);
    oLayout:Add(oList, 0, wx.wxEXPAND);
    oLayout:Add(oHelp, 1, wx.wxEXPAND + wx.wxTOP, 4);
    dPanel:SetSizer(oLayout); dPanel:Hide();
    local oTimer = wx.wxTimer(dPanel);
    local tItems, tDocs = {}, {};
    local nStart, nCompletionPosition;
    local sAppearance;
    local function dismiss()
        dPanel:Hide(); oTimer:Stop();
    end
    tControls[oCode] = dismiss;
    local appearance;
    local function help()
        local nSelection = oList:GetSelection() + 1;
        if (tItems[nSelection]) then oHelp:SetValue(Autocomplete.Describe(tItems[nSelection], tDocs)); end
        if (appearance and dPanel:IsShown()) then appearance(); end
    end
    appearance = function()
        local tSettings = require("Windows.EditorSettings").get();
        local sCurrentAppearance = table.concat({tostring(tSettings.autocompleteUseEditorTheme), tostring(tSettings.autocompleteUseEditorFontSize), tSettings.size, tSettings.theme, tSettings.suggestionBackground, tSettings.suggestionText, tSettings.suggestionFontSize, tSettings.documentationBackground, tSettings.documentationText, tSettings.documentationFontSize, tostring(tSettings.autocompleteHelp)}, ":");
        if (sCurrentAppearance ~= sAppearance) then
            Autocomplete.Style(oList, "suggestion"); Autocomplete.Style(oHelp, "documentation");
            sAppearance = sCurrentAppearance;
        end
        oHelp:Show(tSettings.autocompleteHelp);
        local nListHeight = oList:GetCharHeight() * 5 + 10;
        oList:SetMinSize(wx.wxSize(-1, nListHeight));
        oList:SetMaxSize(wx.wxSize(-1, nListHeight));
        local nLines = 0;
        for sLine in (oHelp:GetValue().."\n"):gmatch("(.-)\n") do
            local sWrapped = ""; nLines = nLines + 1;
            for sWord in sLine:gmatch("%S+") do
                local sCandidate = sWrapped == "" and sWord or sWrapped.." "..sWord;
                local nWidth = oHelp:GetTextExtent(sCandidate);
                if (nWidth > 430 and sWrapped ~= "") then nLines = nLines + 1; sWrapped = sWord;
                else sWrapped = sCandidate; end
            end
        end
        local nDescriptionHeight = math.max(180, nLines * (oHelp:GetCharHeight() + 2) + 24);
        local oSize, oCaret = oCode:GetClientSize(), oCode:PointFromPosition(oCode:GetCurrentPos());
        local nHeight = tSettings.autocompleteHelp and (nListHeight + nDescriptionHeight + 6) or (nListHeight + 2);
        nHeight = math.min(nHeight, math.max(nListHeight + 2, oSize:GetHeight() - 4));
        dPanel:SetSize(wx.wxSize(460, nHeight));
        dPanel:Layout();
        dPanel:Move(wx.wxPoint(math.max(0, math.min(oCaret:GetX(), oSize:GetWidth() - 460)), math.max(0, math.min(oCaret:GetY() + oCode:TextHeight(0), oSize:GetHeight() - nHeight))));
    end
    local function complete()
        local tItem = tItems[oList:GetSelection() + 1];
        if (not tItem) then return; end
        dismiss();
        oCode:SetSelection(nStart, oCode:GetCurrentPos());
        oCode:ReplaceSelection(tItem.name); oCode:SetFocus();
    end
    local function show()
        local tSettings = require("Windows.EditorSettings").get();
        if (not tSettings.autocompleteEnabled) then dismiss(); return; end
        local nPosition = oCode:GetCurrentPos();
        local sTyped = oCode:GetTextRange(0, nPosition):match("([%w_%.]+)$") or "";
        if (#sTyped < tSettings.autocompleteCharacters and sTyped:sub(-1) ~= ".") then dismiss(); return; end
        oCode:Colourise(0, nPosition);
        local nStyle = oCode:GetStyleAt(math.max(0, nPosition - 1));
        if (nStyle == 1 or nStyle == 2 or nStyle == 3 or nStyle == 6 or nStyle == 7 or nStyle == 8 or nStyle == 12) then dismiss(); return; end
        nStart = nPosition - #sTyped;
        nCompletionPosition = nPosition;
        tItems = {};
        local tSeen = {};
        for _, tItem in ipairs(Autocomplete.Read()) do
            local sName = tItem.name;
            if (bRowProcessor and sTyped:sub(1, 4) == "tRow" and (sName:sub(1, 6) == "_tRow." or sName:sub(1, 6) == "_tRow[")) then sName = "tRow"..sName:sub(6); end
            local sMatch = sTyped;
            if (sMatch:sub(-1) == "." and sName:sub(#sMatch, #sMatch) == "[") then sMatch = sMatch:sub(1, -2); end
            if (sName:lower():sub(1, #sMatch) == sMatch:lower() and not tSeen[sName]) then
                tSeen[sName] = true; tItems[#tItems + 1] = {name = sName, kind = tItem.kind};
            end
        end
        table.sort(tItems, function(a, b) return a.name < b.name; end);
        if (#tItems == 0) then dismiss(); return; end
        oList:Clear(); for _, tItem in ipairs(tItems) do oList:Append(tItem.name); end
        oList:SetSelection(0); tDocs = documentation(); help(); appearance(); dPanel:Show(); dPanel:Raise(); oTimer:Start(150);
    end
    oCode:Connect(wxstc.wxEVT_STC_CHARADDED, function(oEvent) show(); oEvent:Skip(); end);
    oCode:Connect(wx.wxEVT_KEY_DOWN, function(oEvent)
        if (not dPanel:IsShown()) then oEvent:Skip(); return; end
        local nKey = oEvent:GetKeyCode();
        if (nKey == wx.WXK_DOWN or nKey == wx.WXK_UP) then
            local nSelection = oList:GetSelection() + (nKey == wx.WXK_DOWN and 1 or -1);
            oList:SetSelection(math.max(0, math.min(nSelection, #tItems - 1))); help();
        elseif (nKey == wx.WXK_RETURN or nKey == wx.WXK_TAB) then complete();
        elseif (nKey == wx.WXK_ESCAPE) then dismiss();
        else
            if (nKey == wx.WXK_LEFT or nKey == wx.WXK_RIGHT or nKey == wx.WXK_HOME or nKey == wx.WXK_END) then dismiss(); end
            oEvent:Skip();
        end
    end);
    oCode:Connect(wx.wxEVT_KEY_UP, function(oEvent)
        if (oEvent:GetKeyCode() == wx.WXK_BACK or oEvent:GetKeyCode() == wx.WXK_DELETE) then show(); end
        oEvent:Skip();
    end);
    oCode:Connect(wxstc.wxEVT_STC_UPDATEUI, function(oEvent)
        if (dPanel:IsShown() and (oCode:GetSelectionStart() ~= oCode:GetSelectionEnd() or oCode:GetCurrentPos() ~= nCompletionPosition)) then dismiss(); end
        oEvent:Skip();
    end);
    oList:Connect(wx.wxEVT_COMMAND_LISTBOX_SELECTED, help);
    oList:Connect(wx.wxEVT_COMMAND_LISTBOX_DOUBLECLICKED, complete);
    oList:Connect(wx.wxEVT_KEY_DOWN, function(oEvent)
        if (oEvent:GetKeyCode() == wx.WXK_RETURN or oEvent:GetKeyCode() == wx.WXK_TAB) then complete();
        elseif (oEvent:GetKeyCode() == wx.WXK_ESCAPE) then dismiss(); oCode:SetFocus();
        else oEvent:Skip(); end
    end);
    dPanel:Connect(oTimer:GetId(), wx.wxEVT_TIMER, function()
        if (not require("Windows.EditorSettings").get().autocompleteEnabled) then dismiss(); return; end
        local oFocus = wx.wxWindow.FindFocus();
        local nFocusID = oFocus and oFocus:GetId();
        if (nFocusID ~= oCode:GetId() and nFocusID ~= oList:GetId() and nFocusID ~= oHelp:GetId()) then dismiss(); return; end
        appearance();
    end);
    oCode:Connect(wx.wxEVT_DESTROY, function(oEvent)
        if (oEvent:GetId() == oCode:GetId()) then oTimer:Stop(); tControls[oCode] = nil; end
        oEvent:Skip();
    end);
    return {panel = dPanel, suggestions = oList, documentation = oHelp, show = show, dismiss = dismiss, complete = complete};
end

return Autocomplete;
